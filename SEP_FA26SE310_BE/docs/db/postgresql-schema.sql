-- Fbus schema snapshot for PostgreSQL 17, matching Flyway V1-V10.
-- Run once in an empty database schema. This file does not create Flyway history.
-- For a database managed by the backend, start the backend with Flyway enabled.
-- Includes migration reference rows only, with no application accounts or demo data.

BEGIN;

-- V1__initial_schema.sql
CREATE TABLE app_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) NOT NULL UNIQUE,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  full_name VARCHAR(150) NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','STUDENT','DRIVER')),
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  preferred_stop_id BIGINT
);
CREATE TABLE auth_session (
  id VARCHAR(36) PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_user(id),
  refresh_hash VARCHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  revoked BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE stop (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(60) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  address VARCHAR(300) NOT NULL
);
ALTER TABLE app_user ADD CONSTRAINT fk_preferred_stop FOREIGN KEY (preferred_stop_id) REFERENCES stop(id);
CREATE TABLE route (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(60) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL
);
CREATE TABLE route_stop (
  route_id BIGINT NOT NULL REFERENCES route(id),
  stop_id BIGINT NOT NULL REFERENCES stop(id),
  position INTEGER NOT NULL CHECK (position >= 0),
  offset_minutes INTEGER NOT NULL CHECK (offset_minutes >= 0),
  PRIMARY KEY (route_id, position),
  UNIQUE (route_id, stop_id)
);
CREATE TABLE trip (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(100) NOT NULL UNIQUE,
  route_id BIGINT NOT NULL REFERENCES route(id),
  departure_at TIMESTAMP NOT NULL,
  arrival_at TIMESTAMP NOT NULL,
  slot INTEGER NOT NULL CHECK (slot BETWEEN 1 AND 6),
  vehicle VARCHAR(30) NOT NULL,
  driver VARCHAR(150) NOT NULL,
  capacity INTEGER NOT NULL CHECK (capacity BETWEEN 1 AND 100),
  status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED' CHECK (status IN ('SCHEDULED','PAUSED')),
  CHECK (arrival_at > departure_at)
);
CREATE INDEX idx_trip_search ON trip (departure_at, route_id);
CREATE TABLE trip_stop (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id BIGINT NOT NULL REFERENCES trip(id),
  stop_id BIGINT NOT NULL REFERENCES stop(id),
  position INTEGER NOT NULL,
  arrival_at TIMESTAMP NOT NULL,
  UNIQUE (trip_id, position),
  UNIQUE (trip_id, stop_id)
);
CREATE TABLE seat (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id BIGINT NOT NULL REFERENCES trip(id),
  code VARCHAR(10) NOT NULL,
  UNIQUE (trip_id, code)
);
CREATE TABLE booking (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(36) NOT NULL UNIQUE,
  user_id BIGINT NOT NULL REFERENCES app_user(id),
  trip_id BIGINT NOT NULL REFERENCES trip(id),
  boarding_trip_stop_id BIGINT NOT NULL REFERENCES trip_stop(id),
  alighting_trip_stop_id BIGINT NOT NULL REFERENCES trip_stop(id),
  boarding_position INTEGER NOT NULL,
  alighting_position INTEGER NOT NULL,
  seat_id BIGINT NOT NULL REFERENCES seat(id),
  status VARCHAR(20) NOT NULL DEFAULT 'RESERVED' CHECK (status IN ('RESERVED','CHECKED_IN','CANCELLED')),
  idempotency_key VARCHAR(100) NOT NULL,
  reserved_at TIMESTAMP NOT NULL,
  checked_in_at TIMESTAMP,
  cancelled_at TIMESTAMP,
  UNIQUE (user_id, idempotency_key),
  CHECK (boarding_position < alighting_position)
);
CREATE INDEX idx_booking_interval ON booking (trip_id, seat_id, status, boarding_position, alighting_position);
CREATE INDEX idx_booking_user ON booking (user_id, reserved_at);
CREATE TABLE operation_lock (name VARCHAR(40) PRIMARY KEY);
INSERT INTO operation_lock(name) VALUES ('trip-schedule');

-- V2__Expand_user_roles.java (PostgreSQL equivalent after V1)
ALTER TABLE app_user DROP CONSTRAINT app_user_role_check;
ALTER TABLE app_user ADD CONSTRAINT chk_user_role
  CHECK (role IN ('ADMIN','STUDENT','DRIVER','BUS_ATTENDANT','LECTURER'));

-- V3__Fleet_and_trip_assignments.sql
CREATE TABLE vehicle (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  license_plate VARCHAR(30) NOT NULL UNIQUE,
  capacity INTEGER NOT NULL CHECK (capacity BETWEEN 1 AND 100),
  driver_id BIGINT NOT NULL REFERENCES app_user(id),
  bus_attendant_id BIGINT REFERENCES app_user(id),
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE'))
);
ALTER TABLE trip ADD COLUMN vehicle_id BIGINT REFERENCES vehicle(id);
ALTER TABLE trip ADD COLUMN driver_id BIGINT REFERENCES app_user(id);
ALTER TABLE trip ADD COLUMN bus_attendant_id BIGINT REFERENCES app_user(id);
ALTER TABLE trip ADD COLUMN bus_attendant VARCHAR(150);
CREATE INDEX idx_trip_driver ON trip(driver_id,departure_at,arrival_at);
CREATE INDEX idx_trip_attendant ON trip(bus_attendant_id,departure_at,arrival_at);
CREATE INDEX idx_trip_vehicle ON trip(vehicle_id,departure_at,arrival_at);

-- V4__Email_access_list.sql
CREATE TABLE email_access (
  email VARCHAR(254) PRIMARY KEY,
  full_name VARCHAR(150) NOT NULL DEFAULT '',
  role VARCHAR(20) NOT NULL CHECK (role IN ('STUDENT','LECTURER','DRIVER','BUS_ATTENDANT')),
  imported_by BIGINT REFERENCES app_user(id),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Preserve access for accounts that were explicitly created before this feature.
INSERT INTO email_access(email,full_name,role)
SELECT LOWER(TRIM(email)),full_name,role FROM app_user WHERE role <> 'ADMIN';
INSERT INTO operation_lock(name) VALUES ('email-access');

-- V5__Wishlist_and_booking_plans.sql
CREATE TABLE trip_wishlist (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_user(id),
  route_id BIGINT NOT NULL REFERENCES route(id),
  boarding_stop_id BIGINT NOT NULL REFERENCES stop(id),
  alighting_stop_id BIGINT NOT NULL REFERENCES stop(id),
  travel_date DATE NOT NULL,
  slot INTEGER NOT NULL CHECK (slot BETWEEN 1 AND 6),
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','CANCELLED','FULFILLED')),
  created_at TIMESTAMP NOT NULL,
  UNIQUE(user_id,route_id,travel_date,slot)
);
CREATE INDEX idx_wishlist_demand ON trip_wishlist(travel_date,slot,status);
CREATE TABLE booking_plan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_user(id),
  route_id BIGINT NOT NULL REFERENCES route(id),
  boarding_stop_id BIGINT NOT NULL REFERENCES stop(id),
  alighting_stop_id BIGINT NOT NULL REFERENCES stop(id),
  slot INTEGER NOT NULL CHECK (slot BETWEEN 1 AND 6),
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  weekdays VARCHAR(20) NOT NULL,
  request_key VARCHAR(100) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','CANCELLED')),
  created_at TIMESTAMP NOT NULL,
  UNIQUE(user_id,request_key),
  CHECK(end_date >= start_date)
);
CREATE TABLE booking_plan_day (
  plan_id BIGINT NOT NULL REFERENCES booking_plan(id),
  travel_date DATE NOT NULL,
  booking_id BIGINT REFERENCES booking(id),
  status VARCHAR(20) NOT NULL CHECK (status IN ('RESERVED','NO_TRIP','FULL','ALREADY_BOOKED','PAST','UNAVAILABLE','CANCELLED')),
  PRIMARY KEY(plan_id,travel_date)
);

-- V6__Trip_recurrence_and_missing_trip_wishlists.sql
ALTER TABLE booking_plan ADD COLUMN wishlist_missing_trips BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE booking_plan_day ADD COLUMN wishlist_id BIGINT REFERENCES trip_wishlist(id);
ALTER TABLE booking_plan_day ADD COLUMN wishlist_created BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE booking_plan_day ADD COLUMN wishlist_note VARCHAR(300);
CREATE TABLE trip_recurrence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_id BIGINT NOT NULL REFERENCES route(id),
  vehicle_id BIGINT REFERENCES vehicle(id),
  vehicle VARCHAR(30) NOT NULL,
  capacity INTEGER NOT NULL CHECK(capacity BETWEEN 1 AND 100),
  driver_id BIGINT REFERENCES app_user(id),
  driver VARCHAR(150) NOT NULL,
  bus_attendant_id BIGINT REFERENCES app_user(id),
  bus_attendant VARCHAR(150),
  departure_time TIME NOT NULL,
  slot INTEGER NOT NULL CHECK(slot BETWEEN 1 AND 6),
  start_date DATE NOT NULL,
  interval_weeks INTEGER NOT NULL CHECK(interval_weeks BETWEEN 1 AND 52),
  weekdays VARCHAR(20) NOT NULL,
  end_type VARCHAR(10) NOT NULL CHECK(end_type IN ('NEVER','UNTIL','COUNT')),
  until_date DATE,
  occurrence_limit INTEGER CHECK(occurrence_limit BETWEEN 1 AND 1000),
  generated_count INTEGER NOT NULL DEFAULT 0,
  processed_through DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','PAUSED','COMPLETED')),
  last_error VARCHAR(300),
  created_by BIGINT NOT NULL REFERENCES app_user(id),
  request_key VARCHAR(100) NOT NULL,
  request_hash VARCHAR(64) NOT NULL,
  created_at TIMESTAMP NOT NULL,
  UNIQUE(created_by,request_key)
);
CREATE TABLE trip_recurrence_day (
  rule_id BIGINT NOT NULL REFERENCES trip_recurrence(id),
  travel_date DATE NOT NULL,
  trip_id BIGINT NOT NULL UNIQUE REFERENCES trip(id),
  PRIMARY KEY(rule_id,travel_date)
);

-- V7__Crew_operations.sql
ALTER TABLE trip ADD COLUMN execution_status VARCHAR(20) NOT NULL DEFAULT 'READY' CHECK (execution_status IN ('READY','IN_PROGRESS','COMPLETED'));
ALTER TABLE trip ADD COLUMN current_stop_position INTEGER NOT NULL DEFAULT -1;
ALTER TABLE trip ADD COLUMN started_at TIMESTAMP;
ALTER TABLE trip ADD COLUMN completed_at TIMESTAMP;
ALTER TABLE booking ADD COLUMN alighted_at TIMESTAMP;
ALTER TABLE booking ADD COLUMN cancellation_reason VARCHAR(30);
CREATE TABLE crew_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 trip_id BIGINT NOT NULL REFERENCES trip(id), user_id BIGINT NOT NULL REFERENCES app_user(id),
 booking_id BIGINT REFERENCES booking(id), action VARCHAR(30) NOT NULL,
 stop_position INTEGER NOT NULL, created_at TIMESTAMP NOT NULL
);
CREATE TABLE trip_report (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 trip_id BIGINT NOT NULL REFERENCES trip(id), reporter_id BIGINT NOT NULL REFERENCES app_user(id),
 category VARCHAR(30) NOT NULL, priority VARCHAR(20) NOT NULL,
 location VARCHAR(200) NOT NULL, description VARCHAR(1000) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','IN_REVIEW','RESOLVED')),
 request_key VARCHAR(100) NOT NULL, created_at TIMESTAMP NOT NULL,
 resolution VARCHAR(500), resolved_by BIGINT REFERENCES app_user(id), updated_at TIMESTAMP,
 UNIQUE(reporter_id,request_key)
);
CREATE INDEX idx_report_status ON trip_report(status,created_at);

-- V8__Dynamic_booking_qr.sql
CREATE TABLE booking_checkin_qr (
 booking_id BIGINT PRIMARY KEY REFERENCES booking(id),
 generation VARCHAR(36) NOT NULL,
 session_id VARCHAR(36) NOT NULL REFERENCES auth_session(id),
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- V9__Booking_priority_windows.sql
CREATE TABLE booking_priority (
 email VARCHAR(254) PRIMARY KEY,
 priority_group VARCHAR(20) NOT NULL CHECK (priority_group IN ('STAFF','STUDENT')),
 updated_by BIGINT NOT NULL REFERENCES app_user(id), updated_at TIMESTAMP NOT NULL
);
INSERT INTO operation_lock(name) VALUES ('booking-priority');
ALTER TABLE trip ADD COLUMN staff_booking_opens_at TIMESTAMP;
ALTER TABLE trip ADD COLUMN priority_student_booking_opens_at TIMESTAMP;
ALTER TABLE trip ADD COLUMN regular_booking_opens_at TIMESTAMP;
ALTER TABLE trip ADD CONSTRAINT chk_trip_booking_opening CHECK (
 (staff_booking_opens_at IS NULL AND priority_student_booking_opens_at IS NULL AND regular_booking_opens_at IS NULL)
 OR (staff_booking_opens_at IS NOT NULL AND priority_student_booking_opens_at IS NOT NULL AND regular_booking_opens_at IS NOT NULL
 AND staff_booking_opens_at<=priority_student_booking_opens_at AND priority_student_booking_opens_at<=regular_booking_opens_at AND regular_booking_opens_at<departure_at));
ALTER TABLE trip_recurrence ADD COLUMN staff_booking_opens_at TIMESTAMP;
ALTER TABLE trip_recurrence ADD COLUMN priority_student_booking_opens_at TIMESTAMP;
