CREATE TABLE app_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) NOT NULL UNIQUE,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  full_name VARCHAR(150) NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','STUDENT','DRIVER')),
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  preferred_stop_id BIGINT
);
CREATE TABLE auth_session (
  id VARCHAR(36) PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_user(id),
  refresh_hash VARCHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  revoked BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE stop (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(60) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  address VARCHAR(300) NOT NULL
);
ALTER TABLE app_user ADD CONSTRAINT fk_preferred_stop FOREIGN KEY (preferred_stop_id) REFERENCES stop(id);
CREATE TABLE route (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(60) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL
);
CREATE TABLE route_stop (
  route_id BIGINT NOT NULL REFERENCES route(id),
  stop_id BIGINT NOT NULL REFERENCES stop(id),
  position INTEGER NOT NULL CHECK (position >= 0),
  offset_minutes INTEGER NOT NULL CHECK (offset_minutes >= 0),
  PRIMARY KEY (route_id, position),
  UNIQUE (route_id, stop_id)
);
CREATE TABLE trip (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(100) NOT NULL UNIQUE,
  route_id BIGINT NOT NULL REFERENCES route(id),
  departure_at TIMESTAMP NOT NULL,
  arrival_at TIMESTAMP NOT NULL,
  slot INTEGER NOT NULL CHECK (slot BETWEEN 1 AND 6),
  vehicle VARCHAR(30) NOT NULL,
  driver VARCHAR(150) NOT NULL,
  capacity INTEGER NOT NULL CHECK (capacity BETWEEN 1 AND 100),
  status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED' CHECK (status IN ('SCHEDULED','PAUSED')),
  CHECK (arrival_at > departure_at)
);
CREATE INDEX idx_trip_search ON trip (departure_at, route_id);
CREATE TABLE trip_stop (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id BIGINT NOT NULL REFERENCES trip(id),
  stop_id BIGINT NOT NULL REFERENCES stop(id),
  position INTEGER NOT NULL,
  arrival_at TIMESTAMP NOT NULL,
  UNIQUE (trip_id, position),
  UNIQUE (trip_id, stop_id)
);
CREATE TABLE seat (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id BIGINT NOT NULL REFERENCES trip(id),
  code VARCHAR(10) NOT NULL,
  UNIQUE (trip_id, code)
);
CREATE TABLE booking (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(36) NOT NULL UNIQUE,
  user_id BIGINT NOT NULL REFERENCES app_user(id),
  trip_id BIGINT NOT NULL REFERENCES trip(id),
  boarding_trip_stop_id BIGINT NOT NULL REFERENCES trip_stop(id),
  alighting_trip_stop_id BIGINT NOT NULL REFERENCES trip_stop(id),
  boarding_position INTEGER NOT NULL,
  alighting_position INTEGER NOT NULL,
  seat_id BIGINT NOT NULL REFERENCES seat(id),
  status VARCHAR(20) NOT NULL DEFAULT 'RESERVED' CHECK (status IN ('RESERVED','CHECKED_IN','CANCELLED')),
  idempotency_key VARCHAR(100) NOT NULL,
  reserved_at TIMESTAMP NOT NULL,
  checked_in_at TIMESTAMP,
  cancelled_at TIMESTAMP,
  UNIQUE (user_id, idempotency_key),
  CHECK (boarding_position < alighting_position)
);
CREATE INDEX idx_booking_interval ON booking (trip_id, seat_id, status, boarding_position, alighting_position);
CREATE INDEX idx_booking_user ON booking (user_id, reserved_at);
CREATE TABLE operation_lock (name VARCHAR(40) PRIMARY KEY);
