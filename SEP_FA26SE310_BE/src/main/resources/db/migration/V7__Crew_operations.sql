CREATE TABLE crew_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 trip_id BIGINT NOT NULL REFERENCES trip(id), user_id BIGINT NOT NULL REFERENCES app_user(id),
 booking_id BIGINT REFERENCES booking(id), action VARCHAR(30) NOT NULL,
 stop_position INTEGER NOT NULL, created_at TIMESTAMP NOT NULL
);
CREATE TABLE trip_report (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 trip_id BIGINT NOT NULL REFERENCES trip(id), reporter_id BIGINT NOT NULL REFERENCES app_user(id),
 category VARCHAR(30) NOT NULL, priority VARCHAR(20) NOT NULL,
 location VARCHAR(200) NOT NULL, description VARCHAR(1000) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','IN_REVIEW','RESOLVED')),
 request_key VARCHAR(100) NOT NULL, created_at TIMESTAMP NOT NULL,
 resolution VARCHAR(500), resolved_by BIGINT REFERENCES app_user(id), updated_at TIMESTAMP,
 UNIQUE(reporter_id,request_key)
);
CREATE INDEX idx_report_status ON trip_report(status,created_at);

