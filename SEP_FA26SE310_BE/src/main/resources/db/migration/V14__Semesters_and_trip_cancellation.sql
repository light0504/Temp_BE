ALTER TABLE trip ADD COLUMN cancelled_by BIGINT REFERENCES app_user(id);
ALTER TABLE trip_recurrence ADD COLUMN semester_id BIGINT REFERENCES semester(id);
ALTER TABLE trip_wishlist ADD COLUMN semester_id BIGINT REFERENCES semester(id);
ALTER TABLE booking_plan ADD COLUMN semester_id BIGINT REFERENCES semester(id);
