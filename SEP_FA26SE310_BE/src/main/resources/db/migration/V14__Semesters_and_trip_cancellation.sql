CREATE TABLE semester (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 term VARCHAR(10) NOT NULL CHECK (term IN ('SPRING','SUMMER','FALL')),
 academic_year INTEGER NOT NULL,
 name VARCHAR(100) NOT NULL,
 start_date DATE NOT NULL,
 end_date DATE NOT NULL,
 UNIQUE(term,academic_year),
 CHECK (start_date<=end_date)
);
ALTER TABLE trip ADD COLUMN semester_id BIGINT REFERENCES semester(id);
ALTER TABLE trip ADD COLUMN cancellation_note VARCHAR(500);
