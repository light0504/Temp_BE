CREATE TABLE trip_recurrence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_id BIGINT NOT NULL REFERENCES route(id),
  vehicle_id BIGINT REFERENCES vehicle(id),
  vehicle VARCHAR(30) NOT NULL,
  capacity INTEGER NOT NULL CHECK(capacity BETWEEN 1 AND 100),
  driver_id BIGINT REFERENCES app_user(id),
  driver VARCHAR(150) NOT NULL,
  bus_attendant_id BIGINT REFERENCES app_user(id),
  bus_attendant VARCHAR(150),
  departure_time TIME NOT NULL,
  slot INTEGER NOT NULL CHECK(slot BETWEEN 1 AND 6),
  start_date DATE NOT NULL,
  interval_weeks INTEGER NOT NULL CHECK(interval_weeks BETWEEN 1 AND 52),
  weekdays VARCHAR(20) NOT NULL,
  end_type VARCHAR(10) NOT NULL CHECK(end_type IN ('NEVER','UNTIL','COUNT')),
  until_date DATE,
  occurrence_limit INTEGER CHECK(occurrence_limit BETWEEN 1 AND 1000),
  generated_count INTEGER NOT NULL DEFAULT 0,
  processed_through DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','PAUSED','COMPLETED')),
  last_error VARCHAR(300),
  created_by BIGINT NOT NULL REFERENCES app_user(id),
  request_key VARCHAR(100) NOT NULL,
  request_hash VARCHAR(64) NOT NULL,
  created_at TIMESTAMP NOT NULL,
  UNIQUE(created_by,request_key)
);
CREATE TABLE trip_recurrence_day (
  rule_id BIGINT NOT NULL REFERENCES trip_recurrence(id),
  travel_date DATE NOT NULL,
  trip_id BIGINT NOT NULL UNIQUE REFERENCES trip(id),
  PRIMARY KEY(rule_id,travel_date)
);
